// Composes baseline (left) | upgraded (right) screenshots with a pixel-diff %
// and writes parity/report/README.md from the Playwright JSON results.
import fs from 'fs';
import path from 'path';
import { PNG } from 'pngjs';
import pixelmatch from 'pixelmatch';

const here = path.dirname(new URL(import.meta.url).pathname);
const shots = path.join(here, 'screenshots');
const out = path.join(here, 'report');
fs.mkdirSync(out, { recursive: true });

const read = f => PNG.sync.read(fs.readFileSync(f));
const pad = (img, w, h) => {
  const p = new PNG({ width: w, height: h });
  p.data.fill(255);
  PNG.bitblt(img, p, 0, 0, img.width, img.height, 0, 0);
  return p;
};

const names = fs.existsSync(path.join(shots, 'baseline'))
  ? fs.readdirSync(path.join(shots, 'baseline')).filter(f => f.endsWith('.png')).sort() : [];
const rows = [];
for (const name of names) {
  const b = path.join(shots, 'baseline', name);
  const u = path.join(shots, 'upgraded', name);
  if (!fs.existsSync(u)) { rows.push({ name, diff: 'missing upgraded' }); continue; }
  const A = read(b), B = read(u);
  const w = Math.max(A.width, B.width), h = Math.max(A.height, B.height);
  const a = pad(A, w, h), c = pad(B, w, h);
  const d = new PNG({ width: w, height: h });
  const px = pixelmatch(a.data, c.data, d.data, w, h, { threshold: 0.1 });
  const pct = (100 * px / (w * h)).toFixed(2);
  const gap = 16;
  const side = new PNG({ width: w * 2 + gap, height: h });
  side.data.fill(255);
  PNG.bitblt(a, side, 0, 0, w, h, 0, 0);
  PNG.bitblt(c, side, 0, 0, w, h, w + gap, 0);
  fs.writeFileSync(path.join(out, name.replace('.png', '.side-by-side.png')), PNG.sync.write(side));
  rows.push({ name, diff: `${pct}%`, sizes: `${A.width}x${A.height} / ${B.width}x${B.height}` });
}

const results = { baseline: {}, upgraded: {} };
const resFile = path.join(here, 'test-results', 'results.json');
if (fs.existsSync(resFile)) {
  const r = JSON.parse(fs.readFileSync(resFile, 'utf8'));
  const walk = (s, file) => {
    for (const sp of s.specs || []) for (const t of sp.tests) {
      const last = t.results[t.results.length - 1];
      results[t.projectName][`${file} › ${sp.title}`] = t.status === 'flaky' ? 'flaky (passed on retry)' : last?.status;
    }
    for (const c of s.suites || []) walk(c, file);
  };
  for (const s of r.suites) walk(s, s.file);
}
const flows = [...new Set([...Object.keys(results.baseline), ...Object.keys(results.upgraded)])].sort();
const count = p => {
  const v = Object.values(results[p]);
  return `${v.filter(x => x && x !== 'failed' && x !== 'timedOut' && x !== 'skipped').length} passed / ${v.filter(x => x === 'failed' || x === 'timedOut').length} failed`;
};

let md = `# Parity report: baseline (Angular 16, :4000) vs upgraded (Angular 21, :4200)\n\n`;
md += `Generated by \`npm run report\` after \`npx playwright test\` (run id ${process.env.PARITY_RUN_ID || 'n/a'}).\n\n`;
md += `- baseline: ${count('baseline')}\n- upgraded: ${count('upgraded')}\n\n`;
md += `The backend is mocked in-browser (see \`support/mock.ts\`); Google Fonts / Material Icons / particles.js CDN requests are blocked in both apps so screenshots are deterministic. \`retries: 1\`.\n\n`;
md += `## Flows\n\n| Page / flow | baseline | upgraded |\n|---|---|---|\n`;
for (const f of flows) md += `| ${f} | ${results.baseline[f] ?? '-'} | ${results.upgraded[f] ?? '-'} |\n`;
md += `\n## Screenshots (baseline left, upgraded right)\n\n| Page | pixel diff | sizes (baseline / upgraded) | side by side |\n|---|---|---|---|\n`;
for (const r of rows) md += `| ${r.name.replace('.png', '')} | ${r.diff} | ${r.sizes ?? ''} | ${r.sizes ? `![](${r.name.replace('.png', '.side-by-side.png')})` : ''} |\n`;
fs.writeFileSync(path.join(out, 'README.md'), md);
console.log(md);
